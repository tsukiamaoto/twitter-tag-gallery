def get_tag_zh(tag_name: str, category: str = "") -> str:
    """回傳標籤的繁體中文名稱（若無對應則回傳空字串）"""
    if not tag_name:
        return ""
    lower = tag_name.lower().strip()
    if category == "artist":
        folder = resolve_artist_folder_name(tag_name)
        return folder if folder in FOLDER_TO_DANBOORU_ARTIST else ""
    if lower in TAG_ZH_DICT:
        return TAG_ZH_DICT[lower]
    return ""


def get_tag_display_name(tag_name: str, category: str = "", zh_name: str = "") -> str:
    """Normalize legacy artist labels without rewriting stored tags or sources."""
    if category != "artist":
        return zh_name or get_tag_zh(tag_name, category)
    known = get_tag_zh(tag_name, category)
    if known:
        return known
    label = (zh_name or "").strip()
    for prefix in ("現有繪師：", "現有繪師:"):
        if label.startswith(prefix):
            label = label[len(prefix):].strip()
            break
    return get_tag_zh(label, "artist") or label or tag_name


# 建立不分大小寫的現有資料夾名稱索引
_EXISTING_FOLDERS_LOWER = {k.lower(): k for k in FOLDER_TO_DANBOORU_ARTIST.keys()}


def resolve_artist_folder_name(artist_tag: str) -> str:
    """
    將繪師標籤名稱解析為適合建立於 D:\\圖檔\\twitter\\ 下的資料夾名稱：
    1. 若對應到現有的 53 個繪師資料夾（例如 chikusa_minori -> 千種みのり），優先使用現有資料夾名稱。
    2. 若為新繪師（例如 moisture_(chichi)、Midori_Xu、@fuumiisc），自動轉為乾淨的繪師資料夾名稱。
    """
    if not artist_tag:
        return ""
    raw = artist_tag.strip()
    if not raw or raw.startswith("pixiv_id:"):
        return ""
    if raw.startswith("twitter:@"):
        raw = raw[len("twitter:@"):].strip()
        if not raw:
            return ""

    lower = raw.lower()
    if lower in DANBOORU_ARTIST_TO_FOLDER:
        return DANBOORU_ARTIST_TO_FOLDER[lower]
    if lower in _EXISTING_FOLDERS_LOWER:
        return _EXISTING_FOLDERS_LOWER[lower]

    # 將底線轉為空白（符合使用者既有資料夾如 'casino (casinoep)', 'box wonderland' 的命名習慣）
    spaced = raw.replace("_", " ").strip()
    if spaced.lower() in DANBOORU_ARTIST_TO_FOLDER:
        return DANBOORU_ARTIST_TO_FOLDER[spaced.lower()]
    if spaced.lower() in _EXISTING_FOLDERS_LOWER:
        return _EXISTING_FOLDERS_LOWER[spaced.lower()]

    # 移除 Windows 資料夾非法字元
    import re
    clean = re.sub(r'[<>:"/\\|?*]', "_", spaced).strip(" .")
    return clean

